export const STRINGS = { en, zh };

/** `t(key, vars)` bound to the current locale; `t.all()` returns the whole table. */
export function createStrings(getLocale) {
  const table = () => (String(getLocale() || '').toLowerCase().startsWith('zh') ? zh : en);
  const t = (key, vars = {}) =>
    (table()[key] ?? en[key] ?? key).replace(/\{(\w+)\}/g, (whole, name) => (name in vars ? String(vars[name]) : whole));
  t.all = () => ({ ...table() });
  return t;
}
